import {createHash} from 'node:crypto';
import {readFile,readdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

export const workerName='folio-offline-worker.js';
const revision=text=>createHash('sha256').update(text).digest('hex');
const templateURL=new URL('./offline-shell-worker.js',import.meta.url);
export async function makeOfflineWorker(root=new URL('../dist/',import.meta.url)){
  const template=await readFile(templateURL,'utf8');
  const rootFiles=await readdir(root,{withFileTypes:true});
  const files=rootFiles.filter(f=>f.isFile()&&f.name!==workerName&&/^[a-z][a-z0-9-]*\.(css|js)$/.test(f.name)).map(f=>f.name);
  files.push('app.html','folio.webmanifest','packs/catalog.js',
    'icons/folio-192.png','icons/folio-512.png','icons/folio-maskable.png','icons/folio-touch.png',
    'vendor/inter/InterVariable.woff2');
  for(const name of ['dejavu-sans','dejavu-serif-condensed','dejavu-serif','noto-sans-display','noto-sans-mono',
    'noto-sans','noto-serif-display','noto-serif','open-sans'])files.push('vendor/reading-fonts/'+name+'.woff2');
  const assets=await Promise.all(files.sort().map(async path=>{
    const bytes=await readFile(new URL(path,root));
    if(!bytes.length||bytes.length>384*1024)throw Error('Offline shell asset must remain small: '+path);
    return {path,bytes:bytes.length,sha256:revision(bytes)};
  }));
  if(assets.length<30||assets.length>145||assets.reduce((n,a)=>n+a.bytes,0)>3*1024*1024)throw Error('Offline application shell budget exceeded');
  const version=revision(template+'\n'+JSON.stringify(assets)).slice(0,24);
  return '/* Generated by tools/update-offline-package.mjs; do not edit. */\n'+template.replace('/* FOLIO_OFFLINE_PACKAGE */null',JSON.stringify({version,assets},null,2));
}
export async function writeOfflineWorker(root=new URL('../dist/',import.meta.url)){
  await writeFile(new URL(workerName,root),await makeOfflineWorker(root));
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))await writeOfflineWorker();
