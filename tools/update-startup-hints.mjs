import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

const origin = new URL('https://folio-build.invalid/reader/');
export const MAX_STARTUP_MODULES = 64;
const MODULE_PATH = /^[a-z0-9_-]+(?:\/[a-z0-9_-]+)*\.(?:js|mjs)$/i;
const START = '<!-- BEGIN generated Folio startup hints -->';
const END = '<!-- END generated Folio startup hints -->';
const dependencyPattern = /^\s*(?:import\s+(?:(?:[^;'"()]*?)\bfrom\s+)?|export\s+(?:\*(?:\s+as\s+\w+)?|\{[^}]*\})\s+from\s+)['"]([^'"]+)['"]/gm;
const scope = path => {
  if (!MODULE_PATH.test(path)) throw new Error('Invalid Folio startup module: ' + path);
  return path;
};
const attributes = tag => Object.fromEntries([...tag.matchAll(/\b([\w-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/gi)].map(x => [x[1].toLowerCase(), x[2] ?? x[3]]));

export async function startupModules(html, load) {
  const roots = [...html.matchAll(/<script\b[^>]*>/gi)].map(m => attributes(m[0]))
    .filter(({type,src}) => type === 'module' && src).map(({src}) => scope(src.replace(/^\.\//, '')));
  if (!roots.length) throw new Error('Folio startup has no module scripts.');
  const graph = new Set([...roots].reverse());
  for (const path of graph) {
    if (graph.size > MAX_STARTUP_MODULES) throw new Error('Recheck startup performance before preloading more modules.');
    const source = await load(path);
    for (const match of source.matchAll(dependencyPattern)) {
      const specifier = match[1];
      if (!/^\.\.?(?:\/)/.test(specifier)) throw new Error('Unexpected startup import: ' + specifier);
      const target = new URL(specifier, new URL(path, origin));
      if (!target.href.startsWith(origin.href)) throw new Error('Startup import escapes reader root: ' + specifier);
      graph.add(scope(target.href.slice(origin.href.length)));
    }
  }
  return [...graph];
}

export function withStartupHints(html, paths) {
  const head = html.indexOf('</head>');
  if (head < 0) throw new Error('Folio startup shell has no head.');
  const prior = html.indexOf(START), end = html.indexOf(END);
  if ((prior >= 0) !== (end >= 0) || (prior >= 0 && (end < prior || end >= head || html.indexOf(START, prior + START.length) >= 0))) {
    throw new Error('Malformed generated startup hints.');
  }
  const before = prior >= 0 ? html.slice(0, prior).replace(/\n$/, '') + html.slice(end + END.length, head).replace(/^\n/, '') : html.slice(0, head);
  const block = [START, '<!-- Generated by tools/update-startup-hints.mjs; defer optional workers and packs. -->',
    '<link rel="preload" as="script" href="boot.js">',
    ...paths.map(path => '<link rel="modulepreload" href="' + scope(path) + '">'), END].join('\n');
  return before + '\n' + block + '\n' + html.slice(head);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const base = new URL('../dist/', import.meta.url);
  const page = new URL('app.html', base);
  const html = await readFile(page, 'utf8');
  const paths = await startupModules(html, path => readFile(new URL(path, base), 'utf8'));
  await writeFile(page, withStartupHints(html, paths));
  console.log('Generated startup hints for', paths.length, 'required static modules.');
}
